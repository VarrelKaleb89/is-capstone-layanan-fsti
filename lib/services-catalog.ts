/** Jumlah layanan per pintu — dihitung dari data aktual. */
export function countByAudience(audience: Audience): number {
  return SERVICES.filter((s) => s.audience === audience).length;
}

/** Pencarian layanan: nama, deskripsi, kategori, kata kunci — case-insensitive. */
export function searchServices(query: string): CatalogService[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\s+/);
  return SERVICES.filter((s) => {
    const haystack = [s.name, s.nameEn ?? '', s.description, s.descriptionEn ?? '', s.category, ...s.keywords]
      .join(' ')
      .toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}
